"""The V7 candidate-family registry.

One record per behavioural family explored in the Luna B discovery phase,
including the ones that were pruned: the multiplicity universe for the later
tournament must be reconstructible from the lineage, not just from the
survivors.

Every record is data, not prose: the JSON registry emitted by
``scripts/v7_discovery_screen.py`` is a direct serialisation of ``FAMILIES``,
and the frozen serious-candidate subset is digested with SHA-256 so a later
independent pass can prove it evaluated what discovery froze.
"""

