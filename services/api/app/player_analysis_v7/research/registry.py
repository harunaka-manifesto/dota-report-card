def registry_payload(names: tuple[str, ...] | None = None) -> dict[str, Any]:
    selected = FAMILIES if names is None else tuple(FAMILY_BY_NAME[name] for name in names)
    return {
        "registry_version": REGISTRY_VERSION,
        "candidate_definition_version": CANDIDATE_DEFINITION_VERSION,
        "families": [family.as_dict() for family in selected],
    }


def canonical_json(payload: dict[str, Any]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def digest(payload: dict[str, Any]) -> str:
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


